export function EmptyState({
  title,
  description,
  action,
  icon,
}: {
  title: string
  description?: string
  action?: ReactNode
  icon?: ReactNode
}) {
  return (
    <div className="flex flex-col items-center justify-center gap-2 py-12 px-6 text-center">
      <div className="text-ink-faint" aria-hidden="true">
        {icon ?? <Inbox className="h-7 w-7" />}
      </div>
      <p className="text-sm font-medium text-ink">{title}</p>
      {description && <p className="text-xs text-ink-muted max-w-md">{description}</p>}
      {action && <div className="mt-2">{action}</div>}
    </div>
  )
}

export function ErrorState({
  error,
  onRetry,
  context,
}: {
  error: unknown
  onRetry?: () => void
  context?: string
}) {
  const message =
    error instanceof Error ? error.message : 'An unexpected error occurred.'
  const code = (error as { code?: string })?.code
  return (
    <div
      className="flex flex-col items-center justify-center gap-2 py-10 px-6 text-center"
      role="alert"
    >
      <AlertTriangle className="h-6 w-6 text-high" aria-hidden="true" />
      <p className="text-sm font-medium text-ink">{context ?? 'Could not load this view'}</p>
      <p className="text-xs text-ink-muted max-w-md">{message}</p>
      {code && <p className="mono text-ink-faint">{code}</p>}
      {onRetry && (
        <button type="button" className="btn-secondary mt-2" onClick={onRetry}>
          Try again
        </button>
      )}
    </div>
  )
}

/** Renders exactly one of loading / error / empty / content. */
export function QueryBoundary<T>({
  query,
  children,
  empty,
  context,
  loadingRows,
}: {
  query: { isLoading: boolean; isError: boolean; error: unknown; data: T | undefined; refetch: () => void }
  children: (data: T) => ReactNode
  empty?: { title: string; description?: string; action?: ReactNode } | ((data: T) => boolean)
  context?: string
  loadingRows?: number
}) {
  if (query.isLoading) return <Loading rows={loadingRows} />
  if (query.isError) return <ErrorState error={query.error} onRetry={query.refetch} context={context} />
  if (query.data === undefined) {
    return <EmptyState title="No data available" />
  }
  if (empty && typeof empty === 'object') {
    const value = query.data as unknown
    const isEmpty =
      Array.isArray(value)
        ? value.length === 0
        : typeof value === 'object' &&
          value !== null &&
          'items' in value &&
          Array.isArray((value as { items: unknown[] }).items) &&
          (value as { items: unknown[] }).items.length === 0
    if (isEmpty) return <EmptyState {...empty} />
  }
  return <>{children(query.data)}</>
}

// --------------------------------------------------------------------- tabs
interface TabsContextValue {
  active: string
  setActive: (value: string) => void
  baseId: string
}
const TabsContext = createContext<TabsContextValue | null>(null)

export function Tabs({
  tabs,
  active,
  onChange,
  children,
  className,
}: {
  tabs: { id: string; label: string; badge?: ReactNode }[]
  active: string
  onChange: (id: string) => void
  children: ReactNode
  className?: string
}) {
  const baseId = useId()

  const onKeyDown = (event: React.KeyboardEvent) => {
    const index = tabs.findIndex((t) => t.id === active)
    if (event.key === 'ArrowRight') {
      event.preventDefault()
      onChange(tabs[(index + 1) % tabs.length].id)
    } else if (event.key === 'ArrowLeft') {
      event.preventDefault()
      onChange(tabs[(index - 1 + tabs.length) % tabs.length].id)
    }
  }

  return (
    <TabsContext.Provider value={{ active, setActive: onChange, baseId }}>
      <div className={className}>
        <div
          role="tablist"
          aria-label="Investigation sections"
          onKeyDown={onKeyDown}
          className="flex items-center gap-1 overflow-x-auto border-b border-line px-1"
        >
          {tabs.map((tab) => {
            const selected = tab.id === active
            return (
              <button
                key={tab.id}
                id={`${baseId}-tab-${tab.id}`}
                role="tab"
                type="button"
                aria-selected={selected}
                aria-controls={`${baseId}-panel-${tab.id}`}
                tabIndex={selected ? 0 : -1}
                onClick={() => onChange(tab.id)}
                className={clsx(
                  'px-3 py-2 text-sm whitespace-nowrap border-b-2 -mb-px transition-colors flex items-center gap-1.5',
                  selected
                    ? 'border-accent text-ink font-medium'
                    : 'border-transparent text-ink-muted hover:text-ink',
                )}
              >
                {tab.label}
                {tab.badge !== undefined && tab.badge !== null && (
                  <span className="text-2xs text-ink-faint tabular-nums">{tab.badge}</span>
                )}
              </button>
            )
          })}
        </div>
        {children}
      </div>
    </TabsContext.Provider>
  )
}

export function TabPanel({ id, children }: { id: string; children: ReactNode }) {
  const context = useContext(TabsContext)
  if (!context || context.active !== id) return null
  return (
    <div
      role="tabpanel"
      id={`${context.baseId}-panel-${id}`}
      aria-labelledby={`${context.baseId}-tab-${id}`}
      tabIndex={0}
      className="animate-slide-up focus-visible:outline-none"
    >
      {children}
    </div>
  )
}

// -------------------------------------------------------------------- modal
export function Modal({
  open,
  onClose,
  title,
  children,
  footer,
  wide,
}: {
  open: boolean
  onClose: () => void
  title: string
  children: ReactNode
  footer?: ReactNode
  wide?: boolean
}) {
  useEffect(() => {
    if (!open) return
    const handler = (event: KeyboardEvent) => {
      if (event.key === 'Escape') onClose()
    }
    document.addEventListener('keydown', handler)
    return () => document.removeEventListener('keydown', handler)
  }, [open, onClose])

  if (!open) return null
  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 animate-fade-in"
      role="dialog"
      aria-modal="true"
      aria-label={title}
      onClick={(event) => {
        if (event.target === event.currentTarget) onClose()
      }}
    >
      <div
        className={clsx(
          'bg-surface border border-line rounded-lg shadow-pop w-full flex flex-col max-h-[85vh]',
          wide ? 'max-w-4xl' : 'max-w-lg',
        )}
      >
        <div className="panel-header">
          <h2 className="text-sm font-semibold">{title}</h2>
          <button type="button" className="btn-ghost p-1" onClick={onClose} aria-label="Close">
            <X className="h-4 w-4" />
          </button>
        </div>
        <div className="p-4 overflow-y-auto flex-1">{children}</div>
        {footer && <div className="px-4 py-3 border-t border-line flex justify-end gap-2">{footer}</div>}
      </div>
    </div>
  )
}

// --------------------------------------------------------------- pagination
export function Pagination({
  total,
  limit,
  offset,
  onChange,
}: {
  total: number
  limit: number
  offset: number
  onChange: (offset: number) => void
}) {
  const page = Math.floor(offset / limit) + 1
  const pages = Math.max(1, Math.ceil(total / limit))
  if (total <= limit) {
    return (
      <p className="text-2xs text-ink-faint px-3 py-2">
        {total} {total === 1 ? 'result' : 'results'}
      </p>
    )
  }
  return (
    <nav className="flex items-center justify-between px-3 py-2 gap-3" aria-label="Pagination">
      <p className="text-2xs text-ink-faint tabular-nums">
        {offset + 1}–{Math.min(offset + limit, total)} of {total}
      </p>
      <div className="flex items-center gap-1">
        <button
          type="button"
          className="btn-ghost px-2 py-1"
          disabled={offset === 0}
          onClick={() => onChange(Math.max(0, offset - limit))}
          aria-label="Previous page"
        >
          <ChevronLeft className="h-4 w-4" />
        </button>
        <span className="text-2xs text-ink-muted tabular-nums px-1">
          {page} / {pages}
        </span>
        <button
          type="button"
          className="btn-ghost px-2 py-1"
          disabled={offset + limit >= total}
          onClick={() => onChange(offset + limit)}
          aria-label="Next page"
        >
          <ChevronRight className="h-4 w-4" />
        </button>
      </div>
    </nav>
  )
}

// ------------------------------------------------------------------- misc
export function CopyButton({ value, label = 'Copy' }: { value: string; label?: string }) {
  const [copied, setCopied] = useState(false)
  const copy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(value)
      setCopied(true)
      setTimeout(() => setCopied(false), 1400)
    } catch {
      /* clipboard unavailable (insecure context) — fail quietly */
    }
  }, [value])

  return (
    <button type="button" className="btn-ghost px-1.5 py-1" onClick={copy} aria-label={label}>
      {copied ? <Check className="h-3.5 w-3.5 text-healthy" /> : <Copy className="h-3.5 w-3.5" />}
    </button>
  )
}

