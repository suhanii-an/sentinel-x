// --------------------------------------------------------------- page states
export function Loading({ label = 'Loading', rows = 3 }: { label?: string; rows?: number }) {
  return (
    <div className="p-4 space-y-2" role="status" aria-live="polite" aria-busy="true">
      <span className="sr-only">{label}</span>
      {Array.from({ length: rows }).map((_, index) => (
        <div
          key={index}
          className="relative h-8 rounded bg-raised/60 overflow-hidden"
          style={{ opacity: 1 - index * 0.15 }}
        >
          <div className="absolute inset-0 -translate-x-full animate-shimmer bg-gradient-to-r from-transparent via-line/40 to-transparent" />
        </div>
      ))}
    </div>
  )
}

