export function Callout({
  tone = 'info',
  title,
  children,
}: {
  tone?: 'info' | 'warning' | 'critical' | 'healthy'
  title?: string
  children: ReactNode
}) {
  const tones = {
    info: 'border-low/40 bg-low/5 text-ink-muted',
    warning: 'border-medium/40 bg-medium/5 text-ink-muted',
    critical: 'border-critical/40 bg-critical/5 text-ink-muted',
    healthy: 'border-healthy/40 bg-healthy/5 text-ink-muted',
  }
  return (
    <div className={clsx('border rounded-md p-3 text-xs leading-relaxed', tones[tone])}>
      {title && <p className="font-semibold text-ink mb-1">{title}</p>}
      {children}
    </div>
  )
}

export function ProgressBar({
  value,
  max = 100,
  color = '#22d3ee',
  label,
}: {
  value: number
  max?: number
  color?: string
  label?: string
}) {
  const pct = max > 0 ? Math.min(100, Math.max(0, (value / max) * 100)) : 0
  return (
    <div
      className="h-1.5 w-full bg-raised rounded-full overflow-hidden"
      role="progressbar"
      aria-valuenow={value}
      aria-valuemin={0}
      aria-valuemax={max}
      aria-label={label}
    >
      <div className="h-full rounded-full transition-all" style={{ width: `${pct}%`, backgroundColor: color }} />
    </div>
  )
}
